//! Refusal remedies: move an unmanaged path into the support `.moved-aside` area (TF-042).
//!
//! This module is the TF-042 primitive. It is deliberately separate from
//! [`crate::guard::move_aside`], which implements TF-005's same-parent rename with the
//! `*.agentuna-backup-*` name: that function stays unchanged and keeps its TF-005 behaviour.
//! The move here is a second, additive remedy that:
//!
//! 1. renames the unmanaged file or directory (or, across devices, copies, verifies hashes and
//!    deletes the source) into `<support>/.moved-aside/<UTC timestamp>/<encoded absolute path>`;
//! 2. asks a [`MoveJournal`] to record an `operations` row with action [`MoveAction::Moved`] and
//!    the inverse mapping ([`MoveRecord::inverse`]);
//! 3. returns [`MoveAsideOutcome`] with the operation id, so [`undo_move`] can move it back.
//!
//! **Adopt is not implemented here.** [`RefusalRemedies`] only names the TC-011 adopt flow:
//! the at-fs crate writes no adopt bytes and defines no adopt-code symbol.
//!
//! The `MoveJournal` is a trait because `at-db`'s operations API (TF-009) is not implemented
//! yet and `at-fs` must not depend on `at-db`. The engine supplies the real journal; tests use
//! an in-memory one. Until TF-009 lands no production operations row is written by this crate.

use std::ffi::OsStr;
use std::fmt;
use std::fs;
use std::io;
use std::path::{Component, Path, PathBuf};

use time::OffsetDateTime;
use time::format_description::FormatItem;
use time::macros::format_description;

use crate::error::FsError;
use crate::hash::sha256_hex;
use crate::{MAX_FILE_BYTES, guard};

/// Directory under the support directory that holds moved-aside paths.
pub const MOVED_ASIDE_DIR_NAME: &str = ".moved-aside";

/// The `operations.action` value every move writes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum MoveAction {
    /// The file or directory was moved aside.
    Moved,
}

impl MoveAction {
    /// The text stored in `operations.action`.
    #[must_use]
    pub const fn as_db(self) -> &'static str {
        match self {
            Self::Moved => "moved",
        }
    }
}

/// How the bytes reached the moved-aside location.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum MoveStrategy {
    /// A same-volume atomic rename; no byte was copied.
    Rename,
    /// A cross-device copy that was hash-verified before the source was deleted.
    CopyVerified,
}

impl MoveStrategy {
    /// The text recorded alongside the operation.
    #[must_use]
    pub const fn as_db(self) -> &'static str {
        match self {
            Self::Rename => "rename",
            Self::CopyVerified => "copy_verified",
        }
    }
}

/// A move that reverses another move.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InverseMove {
    /// Path to move from when undoing (the moved-aside location).
    pub from: PathBuf,
    /// Path to move back to (the original path).
    pub to: PathBuf,
}

/// Identifier of the `operations` row a move wrote.
///
/// When TF-009 lands this is the same value as `at_model::OperationId`; it is a plain string so
/// this crate needs no dependency on the DB layer.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct MoveOperationId(String);

impl MoveOperationId {
    /// Wraps an id generated by a journal.
    #[must_use]
    pub fn new(raw: impl Into<String>) -> Self {
        Self(raw.into())
    }

    /// The raw id text.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for MoveOperationId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// The row a journal must record before a byte is moved.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MoveDraft {
    /// Always [`MoveAction::Moved`] today.
    pub action: MoveAction,
    /// The path that is being moved.
    pub original: PathBuf,
    /// Where it is going.
    pub moved_to: PathBuf,
    /// The mapping that reverses the move.
    pub inverse: InverseMove,
}

/// A finished move turned back by [`undo_move`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UndoMoveOutcome {
    /// Path the entry was restored to.
    pub original: PathBuf,
    /// Moved-aside path the entry came from.
    pub moved_back_from: PathBuf,
    /// Operation that was undone.
    pub operation_id: MoveOperationId,
}

/// The operations-log seam a move writes through.
///
/// `begin` is called before the filesystem changes, so a crash between the two leaves a visible
/// pending row. `complete` records the strategy that was used; `fail` records an attempted move
/// that did not happen. `lookup` returns the row for undo, and `mark_undone` closes it.
pub trait MoveJournal: fmt::Debug {
    /// Starts the operations row and returns its id.
    ///
    /// # Errors
    /// Any database failure; when this returns an error nothing is moved.
    fn begin(&self, draft: MoveDraft) -> Result<MoveOperationId, FsError>;
    /// Records that the move completed with `strategy`.
    ///
    /// # Errors
    /// Any database failure.
    fn complete(
        &self,
        operation_id: &MoveOperationId,
        strategy: MoveStrategy,
    ) -> Result<(), FsError>;
    /// Records that the move failed; the inverse is retained for diagnosis.
    ///
    /// # Errors
    /// Any database failure.
    fn fail(&self, operation_id: &MoveOperationId, reason: &str) -> Result<(), FsError>;
    /// Returns the recorded move, if the id exists.
    ///
    /// # Errors
    /// Any database failure.
    fn lookup(&self, operation_id: &MoveOperationId) -> Result<Option<MoveRecord>, FsError>;
    /// Marks the operation as undone after [`undo_move`] succeeded.
    ///
    /// # Errors
    /// Any database failure.
    fn mark_undone(&self, operation_id: &MoveOperationId) -> Result<(), FsError>;
}

/// A recorded move, as returned by [`MoveJournal::lookup`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MoveRecord {
    /// The operations row id.
    pub operation_id: MoveOperationId,
    /// The action that was recorded.
    pub action: MoveAction,
    /// The path that was moved.
    pub original: PathBuf,
    /// Where it was moved to.
    pub moved_to: PathBuf,
    /// How the bytes arrived.
    pub strategy: MoveStrategy,
    /// The mapping that reverses the move.
    pub inverse: InverseMove,
}

/// The filesystem calls a move needs. Injected so EXDEV and interrupted copies are testable.
#[doc(hidden)]
pub trait MoveFs: fmt::Debug {
    /// Renames a path; returns `EXDEV` when the paths are on different devices.
    fn rename(&self, from: &Path, to: &Path) -> io::Result<()>;
    /// Copies a tree into an absent destination.
    fn copy_tree(&self, from: &Path, to: &Path) -> io::Result<()>;
    /// Deletes a file or a whole tree.
    fn remove_tree(&self, path: &Path) -> io::Result<()>;
}

/// The real filesystem.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct SystemMoveFs;

impl MoveFs for SystemMoveFs {
    fn rename(&self, from: &Path, to: &Path) -> io::Result<()> {
        fs::rename(from, to)
    }

    fn copy_tree(&self, from: &Path, to: &Path) -> io::Result<()> {
        copy_tree(from, to)
    }

    fn remove_tree(&self, path: &Path) -> io::Result<()> {
        match fs::symlink_metadata(path) {
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e),
            Ok(meta) if meta.is_dir() => fs::remove_dir_all(path),
            Ok(_) => fs::remove_file(path),
        }
    }
}

/// Everything one move needs.
#[derive(Debug, Clone)]
pub struct MoveAsideRequest {
    /// The support directory (`AppPaths::support_dir`).
    pub support_dir: PathBuf,
    /// The unmanaged file or directory to move.
    pub path: PathBuf,
    /// Clock value used for the timestamp directory and the operation record.
    pub now: OffsetDateTime,
}

impl MoveAsideRequest {
    /// A request for `path` under `support_dir` at `now`.
    #[must_use]
    pub fn new(
        support_dir: impl Into<PathBuf>,
        path: impl Into<PathBuf>,
        now: OffsetDateTime,
    ) -> Self {
        Self {
            support_dir: support_dir.into(),
            path: path.into(),
            now,
        }
    }
}

/// Where a moved path went.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MoveAsideOutcome {
    /// The path that was moved.
    pub original: PathBuf,
    /// Its new location under `<support>/.moved-aside/<timestamp>/...`.
    pub moved_to: PathBuf,
    /// The recorded operation id, usable with [`undo_move`].
    pub operation_id: MoveOperationId,
}

const STAMP: &[FormatItem<'static>] =
    format_description!("[year][month][day]T[hour][minute][second]Z");

/// Moves `path` into `<support>/.moved-aside/<UTC timestamp>/<encoded absolute path>`.
///
/// The whole tree moves; nothing is copied on one volume and every byte is preserved. Across
/// devices (`EXDEV`) the tree is copied, hash-verified and only then is the source removed, so
/// an interrupted copy leaves the source untouched.
///
/// A [`MoveJournal`] row is written before the filesystem changes; the inverse mapping is
/// [`MoveRecord::inverse`].
///
/// # Errors
/// [`FsError::NotFound`] when `path` does not exist, [`FsError::PermissionDenied`] on a
/// read-only volume (nothing changes), [`FsError::CopyVerificationFailed`] when a cross-device
/// copy does not match, and journal errors from `begin`.
pub fn move_aside(
    request: &MoveAsideRequest,
    journal: &dyn MoveJournal,
) -> Result<MoveAsideOutcome, FsError> {
    move_aside_with(request, journal, &SystemMoveFs)
}

/// [`move_aside`] with an injected filesystem. For tests.
#[doc(hidden)]
pub fn move_aside_with(
    request: &MoveAsideRequest,
    journal: &dyn MoveJournal,
    fs_impl: &dyn MoveFs,
) -> Result<MoveAsideOutcome, FsError> {
    let support = guard::clean_absolute(&request.support_dir)?;
    let original = guard::clean_absolute(&request.path)?;
    let moved_aside_root = support.join(MOVED_ASIDE_DIR_NAME);
    if original.starts_with(&moved_aside_root) {
        return Err(FsError::InvalidPath {
            path: original,
            reason: "path is already inside .moved-aside",
        });
    }
    if support.starts_with(&original) {
        return Err(FsError::InvalidPath {
            path: original,
            reason: "the support directory is inside the path being moved",
        });
    }
    fs::symlink_metadata(&original).map_err(|e| FsError::from_io(&original, e))?;

    let stamp = request
        .now
        .to_offset(time::UtcOffset::UTC)
        .format(STAMP)
        .map_err(|_| FsError::InvalidPath {
            path: original.clone(),
            reason: "timestamp not formattable",
        })?;
    let encoded = encode_path(&original)?;
    let moved_to = unique_destination(&moved_aside_root.join(stamp).join(encoded))?;

    let inverse = InverseMove {
        from: moved_to.clone(),
        to: original.clone(),
    };
    let draft = MoveDraft {
        action: MoveAction::Moved,
        original: original.clone(),
        moved_to: moved_to.clone(),
        inverse,
    };
    let operation_id = journal.begin(draft)?;

    match perform_move(&original, &moved_to, fs_impl) {
        Ok(strategy) => {
            journal.complete(&operation_id, strategy)?;
            Ok(MoveAsideOutcome {
                original,
                moved_to,
                operation_id,
            })
        }
        Err(error) => {
            // The move failure is what the caller must see; a journal failure here cannot be
            // allowed to mask it. The pending row stays visible to the engine.
            let _ = journal.fail(&operation_id, &error.to_string());
            Err(error)
        }
    }
}

/// Moves a recorded entry back to its original path.
///
/// The original must be absent, so undo never clobbers a newer external edit. Works for both
/// [`MoveStrategy::Rename`] and [`MoveStrategy::CopyVerified`] records.
///
/// # Errors
/// [`FsError::NotFound`] when the operation id or the moved-aside path is missing,
/// [`FsError::AlreadyExists`] when the original path is occupied again, plus the move errors.
pub fn undo_move(
    operation_id: &MoveOperationId,
    journal: &dyn MoveJournal,
    fs_impl: &dyn MoveFs,
) -> Result<UndoMoveOutcome, FsError> {
    let record = journal
        .lookup(operation_id)?
        .ok_or_else(|| FsError::NotFound {
            path: PathBuf::from(operation_id.as_str()),
        })?;
    if fs::symlink_metadata(&record.original).is_ok() {
        return Err(FsError::AlreadyExists {
            path: record.original,
        });
    }
    fs::symlink_metadata(&record.moved_to).map_err(|e| FsError::from_io(&record.moved_to, e))?;
    perform_move(&record.moved_to, &record.original, fs_impl)?;
    journal.mark_undone(operation_id)?;
    Ok(UndoMoveOutcome {
        original: record.original,
        moved_back_from: record.moved_to,
        operation_id: operation_id.clone(),
    })
}

fn perform_move(from: &Path, to: &Path, fs_impl: &dyn MoveFs) -> Result<MoveStrategy, FsError> {
    if let Some(parent) = to.parent() {
        fs::create_dir_all(parent).map_err(|e| FsError::from_io(parent, e))?;
    }
    match fs_impl.rename(from, to) {
        Ok(()) => Ok(MoveStrategy::Rename),
        Err(error) if error.raw_os_error() == Some(libc::EXDEV) => {
            copy_verified_move(from, to, fs_impl)
        }
        Err(error) => Err(FsError::from_io(from, error)),
    }
}

fn copy_verified_move(
    from: &Path,
    to: &Path,
    fs_impl: &dyn MoveFs,
) -> Result<MoveStrategy, FsError> {
    let stage = unique_destination(&sibling_stage_path(to)?)?;
    let source_digest = digest_tree(from)?;
    if let Some(parent) = stage.parent() {
        fs::create_dir_all(parent).map_err(|e| FsError::from_io(parent, e))?;
    }
    if let Err(error) = fs_impl.copy_tree(from, &stage) {
        remove_quietly(&stage);
        return Err(FsError::from_io(&stage, error));
    }
    let copied_digest = match digest_tree(&stage) {
        Ok(digest) => digest,
        Err(error) => {
            remove_quietly(&stage);
            return Err(error);
        }
    };
    if source_digest != copied_digest {
        remove_quietly(&stage);
        return Err(FsError::CopyVerificationFailed {
            path: from.to_path_buf(),
            reason: "the copy does not match the source hashes".to_owned(),
        });
    }
    // The stage is a sibling of the destination, so installing it is a same-volume rename. The
    // injected filesystem is only trusted for the cross-device rename of the source.
    if let Err(error) = fs::rename(&stage, to) {
        remove_quietly(&stage);
        return Err(FsError::from_io(&stage, error));
    }
    fs_impl
        .remove_tree(from)
        .map_err(|e| FsError::from_io(from, e))?;
    Ok(MoveStrategy::CopyVerified)
}

fn sibling_stage_path(to: &Path) -> Result<PathBuf, FsError> {
    let parent = to.parent().ok_or_else(|| FsError::NoParent {
        path: to.to_path_buf(),
    })?;
    let name = to
        .file_name()
        .ok_or_else(|| FsError::NoParent {
            path: to.to_path_buf(),
        })?
        .to_string_lossy()
        .into_owned();
    Ok(parent.join(format!(".{name}.partial-{}", std::process::id())))
}

fn unique_destination(preferred: &Path) -> Result<PathBuf, FsError> {
    for attempt in 0u32..1000 {
        let candidate = if attempt == 0 {
            preferred.to_path_buf()
        } else {
            let name = preferred
                .file_name()
                .map(|name| name.to_string_lossy().into_owned())
                .unwrap_or_default();
            preferred.with_file_name(format!("{name}.{attempt}"))
        };
        if fs::symlink_metadata(&candidate).is_err() {
            return Ok(candidate);
        }
    }
    Err(FsError::AlreadyExists {
        path: preferred.to_path_buf(),
    })
}

fn remove_quietly(path: &Path) {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.is_dir() => {
            let _ = fs::remove_dir_all(path);
        }
        Ok(_) => {
            let _ = fs::remove_file(path);
        }
        Err(_) => {}
    }
}

/// Encodes an absolute path as one relative file name.
///
/// Each component's bytes outside `A-Z`, `a-z`, `0-9`, `.`, `_` and `-` are written as `%XX`
/// (so a literal `%` becomes `%25`), and components are joined with the literal `%2F`. The
/// result is a legal single file name on every platform, cannot escape the timestamp directory,
/// and cannot collide through prefixes: a path and a path below it get different names. The
/// root component is dropped; `..` is refused before this runs.
///
/// # Errors
/// [`FsError::InvalidPath`] for a path with no normal components.
pub fn encode_path(path: &Path) -> Result<PathBuf, FsError> {
    let mut encoded = String::new();
    for component in path.components() {
        match component {
            Component::RootDir | Component::CurDir => {}
            Component::ParentDir => {
                return Err(FsError::InvalidPath {
                    path: path.to_path_buf(),
                    reason: "path must not contain `..`",
                });
            }
            Component::Prefix(prefix) => push_encoded(&mut encoded, prefix.as_os_str()),
            Component::Normal(name) => push_encoded(&mut encoded, name),
        }
    }
    if encoded.is_empty() {
        return Err(FsError::InvalidPath {
            path: path.to_path_buf(),
            reason: "path has no component to encode",
        });
    }
    Ok(PathBuf::from(encoded))
}

fn push_encoded(encoded: &mut String, component: &OsStr) {
    if !encoded.is_empty() {
        encoded.push_str("%2F");
    }
    encoded.push_str(&encode_component(component));
}

fn encode_component(component: &OsStr) -> String {
    #[cfg(unix)]
    let bytes = std::os::unix::ffi::OsStrExt::as_bytes(component);
    #[cfg(not(unix))]
    let bytes = component.to_string_lossy().as_bytes().to_vec();
    let mut out = String::with_capacity(bytes.len());
    for &byte in bytes.iter() {
        let keep = byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-');
        if keep {
            out.push(char::from(byte));
        } else {
            out.push('%');
            out.push_str(&format!("{byte:02X}"));
        }
    }
    out
}

/// SHA-256 over the sorted tree: every relative path, file hash and size, directory marker and
/// symlink target. Used to verify a cross-device copy before the source is deleted.
fn digest_tree(root: &Path) -> Result<String, FsError> {
    let mut buffer = String::new();
    digest_into(root, root, &mut buffer)?;
    Ok(sha256_hex(buffer.as_bytes()))
}

fn digest_into(root: &Path, dir: &Path, buffer: &mut String) -> Result<(), FsError> {
    let mut entries = fs::read_dir(dir)
        .map_err(|e| FsError::from_io(dir, e))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| FsError::from_io(dir, e))?;
    entries.sort_by_key(fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        let relative = path.strip_prefix(root).map_err(|_| FsError::InvalidPath {
            path: path.clone(),
            reason: "entry is outside the moved tree",
        })?;
        let relative = relative.to_string_lossy();
        let meta = fs::symlink_metadata(&path).map_err(|e| FsError::from_io(&path, e))?;
        if meta.file_type().is_symlink() {
            let target = fs::read_link(&path).map_err(|e| FsError::from_io(&path, e))?;
            buffer.push_str(&relative);
            buffer.push_str("\0link\0");
            buffer.push_str(&target.to_string_lossy());
            buffer.push('\n');
        } else if meta.is_dir() {
            buffer.push_str(&relative);
            buffer.push_str("\0dir\n");
            digest_into(root, &path, buffer)?;
        } else if meta.is_file() {
            if meta.len() > MAX_FILE_BYTES {
                return Err(FsError::TooLarge {
                    path,
                    size: meta.len(),
                    limit: MAX_FILE_BYTES,
                });
            }
            let bytes = fs::read(&path).map_err(|e| FsError::from_io(&path, e))?;
            buffer.push_str(&relative);
            buffer.push('\0');
            buffer.push_str(&sha256_hex(&bytes));
            buffer.push('\0');
            buffer.push_str(&bytes.len().to_string());
            buffer.push('\n');
        } else {
            return Err(FsError::NotRegularFile { path });
        }
    }
    Ok(())
}

fn copy_tree(from: &Path, to: &Path) -> io::Result<()> {
    let meta = fs::symlink_metadata(from)?;
    if meta.file_type().is_symlink() {
        let target = fs::read_link(from)?;
        #[cfg(unix)]
        {
            return std::os::unix::fs::symlink(target, to);
        }
        #[cfg(not(unix))]
        {
            let _ = target;
            return Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "symbolic links cannot be recreated on this platform",
            ));
        }
    }
    if meta.is_dir() {
        fs::create_dir(to)?;
        let mut entries = fs::read_dir(from)?.collect::<Result<Vec<_>, _>>()?;
        entries.sort_by_key(fs::DirEntry::file_name);
        for entry in entries {
            copy_tree(&entry.path(), &to.join(entry.file_name()))?;
        }
        // Apply the source mode after the children exist: a read-only source directory would
        // otherwise stop the copy from creating them.
        fs::set_permissions(to, meta.permissions())?;
        return Ok(());
    }
    if meta.is_file() {
        fs::copy(from, to)?;
        fs::set_permissions(to, meta.permissions())?;
        return Ok(());
    }
    Err(io::Error::new(
        io::ErrorKind::InvalidInput,
        format!(
            "{}: not a regular file, directory or symlink",
            from.display()
        ),
    ))
}

/// The stable id of the TC-011 adopt flow. TF-042 routes Adopt there; it implements no adopt.
pub const ADOPT_FLOW_ID: &str = "TC-011";

/// One button offered when AgenTuna refuses to overwrite something.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum RefusalRemedy {
    /// Open the TC-011 adopt flow, which owns copying, id assignment and linking.
    AdoptVia {
        /// Flow id; always [`ADOPT_FLOW_ID`] for the standard entry.
        flow_id: &'static str,
    },
    /// Move the existing entry into `.moved-aside`.
    MoveAside,
    /// Do nothing.
    Cancel,
}

/// The remedy value a refusal carries to the UI and the CLI.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RefusalRemedies {
    remedies: [RefusalRemedy; 3],
}

impl RefusalRemedies {
    /// Adopt (via TC-011), Move aside, Cancel — in that order.
    #[must_use]
    pub const fn standard() -> Self {
        Self {
            remedies: [
                RefusalRemedy::AdoptVia {
                    flow_id: ADOPT_FLOW_ID,
                },
                RefusalRemedy::MoveAside,
                RefusalRemedy::Cancel,
            ],
        }
    }

    /// The offered remedies in display order.
    #[must_use]
    pub fn remedies(&self) -> &[RefusalRemedy] {
        &self.remedies
    }

    /// The adopt flow id, proving Adopt resolves to TC-011 and not to code in this crate.
    #[must_use]
    pub fn adopt_flow_id(&self) -> Option<&'static str> {
        self.remedies.iter().find_map(|remedy| match remedy {
            RefusalRemedy::AdoptVia { flow_id } => Some(*flow_id),
            _ => None,
        })
    }

    /// The same value as at-model [`at_model::Remedy`] buttons, for the guard and the UI.
    #[must_use]
    pub fn model_remedies(&self) -> Vec<at_model::Remedy> {
        self.remedies
            .iter()
            .map(|remedy| match remedy {
                RefusalRemedy::AdoptVia { .. } => at_model::Remedy::Adopt,
                RefusalRemedy::MoveAside => at_model::Remedy::MoveAside,
                RefusalRemedy::Cancel => at_model::Remedy::Cancel,
            })
            .collect()
    }
}

impl Default for RefusalRemedies {
    fn default() -> Self {
        Self::standard()
    }
}
