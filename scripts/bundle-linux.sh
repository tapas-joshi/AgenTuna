#!/usr/bin/env bash
# Builds the Linux release artifacts into dist/ for the host architecture
# (the release workflow builds x86_64; aarch64 is labelled correctly but untested).
#
# Produces:
#   dist/AgenTuna-<version>-linux-<arch>.tar.gz          portable tree: the GUI binary, the
#                                                        CLI, the canonical desktop entry, the
#                                                        hicolor icons, install-linux.sh, LICENSE
#   dist/agentuna-cli-<version>-linux-<arch>.tar.gz      the CLI alone
#   dist/AgenTuna-<version>-linux-<arch>.deb             with --bundler or --bundler-only
#   dist/AgenTuna-<version>-linux-<arch>.AppImage        with --bundler or --bundler-only
#
# The tarball mirrors the repository layout scripts/install-linux.sh already expects
# (target/release/agentuna-app, crates/at-app/icons/*, scripts/install-linux.sh), so
# extracting it and running `scripts/install-linux.sh` installs the XDG desktop integration
# with no arguments. The desktop entry is extracted from the DESKTOP_ENTRY constant in
# crates/at-app/src/app/linux.rs, which stays the single source of that text.
#
# The .deb and .AppImage come from the Tauri bundler through
# crates/at-app/tauri.linux.conf.json. They are best effort: bundling downloads the Tauri
# AppImage tooling and no automated test launches either package yet. The tarball is the
# artifact that always exists.
#
# Options:
#   --bundler       also build the .deb and .AppImage through the Tauri bundler
#   --bundler-only  run only the Tauri bundler; everything is already built
#   --dry-run       print the plan without building or writing anything
#   -h, --help      show this help

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET_DIR="${CARGO_TARGET_DIR:-$ROOT/target}"
DIST="$ROOT/dist"
BUNDLER=0
BUNDLER_ONLY=0
DRY_RUN=0

usage() {
    cat <<EOF
Usage: scripts/bundle-linux.sh [options]

Builds the Linux release artifacts into $DIST.

  --bundler       also build the .deb and .AppImage through the Tauri bundler
  --bundler-only  run only the Tauri bundler; skip the cargo builds and the tarballs
  --dry-run       print the plan without building or writing anything
  -h, --help      show this help
EOF
}

fail() {
    echo "error: $*" >&2
    exit 1
}

note() {
    echo "==> $*"
}

# Echoes the command as `+ ...` and runs it unless this is a dry run.
run() {
    printf '+'
    printf ' %q' "$@"
    printf '\n'
    if (( DRY_RUN )); then
        return 0
    fi
    "$@"
}

run_in() {
    local dir="$1"
    shift
    printf '+ (cd %q &&' "$dir"
    printf ' %q' "$@"
    printf ')\n'
    if (( DRY_RUN )); then
        return 0
    fi
    (cd "$dir" && "$@")
}

while (( $# > 0 )); do
    case "$1" in
        --bundler) BUNDLER=1; shift ;;
        --bundler-only) BUNDLER=1; BUNDLER_ONLY=1; shift ;;
        --dry-run) DRY_RUN=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "error: unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
done

# --- Preconditions -----------------------------------------------------------

[[ -f "$ROOT/Cargo.toml" ]] || fail "not inside the AgenTuna repository (no Cargo.toml)"
[[ -f "$ROOT/LICENSE" ]] || fail "missing LICENSE: $ROOT/LICENSE"

if (( ! DRY_RUN )); then
    [[ "$(uname -s)" == "Linux" ]] \
        || fail "the Linux artifacts must be built on Linux; use --dry-run elsewhere to see the plan"
fi

VERSION="$(sed -n '/^\[workspace.package\]/,/^\[/p' "$ROOT/Cargo.toml" \
    | sed -n 's/^version[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' \
    | head -n 1)"
[[ -n "$VERSION" ]] || fail "missing workspace version in $ROOT/Cargo.toml"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || fail "workspace version is not semver: $VERSION"

case "$(uname -m)" in
    x86_64|amd64) ARCH="x86_64" ;;
    aarch64|arm64) ARCH="aarch64" ;;
    *) fail "unsupported architecture: $(uname -m)" ;;
esac

STAGE_NAME="AgenTuna-$VERSION-linux-$ARCH"
CLI_STAGE_NAME="agentuna-cli-$VERSION-linux-$ARCH"
STAGE="$DIST/$STAGE_NAME"
CLI_STAGE="$DIST/$CLI_STAGE_NAME"
ICONS=(32x32.png 128x128.png 128x128@2x.png)

# The desktop entry is generated by install-linux.sh at install time; the tarball also carries
# this copy so a package manager or a curious user can read it without running the script.
desktop_entry() {
    sed -n '/^pub const DESKTOP_ENTRY: &str/,/^";$/p' "$ROOT/crates/at-app/src/app/linux.rs" \
        | sed '1d;$d'
}

ENTRY="$(desktop_entry)"
[[ "$ENTRY" == "[Desktop Entry]"* ]] \
    || fail "the DESKTOP_ENTRY constant in crates/at-app/src/app/linux.rs did not parse"
[[ "$ENTRY" == *"Exec=agentuna-app"* ]] \
    || fail "the extracted desktop entry does not launch agentuna-app"
[[ "$ENTRY" == *"Icon=agentuna"* ]] \
    || fail "the extracted desktop entry does not name the agentuna icon"

# --- Build -------------------------------------------------------------------

if (( ! BUNDLER_ONLY )); then
    [[ -f "$ROOT/crates/at-app/icons/${ICONS[0]}" ]] \
        || fail "missing icon sources: $ROOT/crates/at-app/icons"
    if (( ! DRY_RUN )); then
        [[ -d "$ROOT/ui/node_modules" ]] \
            || fail "UI dependencies missing; run: pnpm --dir ui install --frozen-lockfile"
    fi

    echo "==> Building the UI assets the Tauri app embeds"
    run_in "$ROOT" pnpm --dir ui build

    echo "==> Building the release binaries"
    # `--features custom-protocol` is what `tauri build` sets for a release build: it makes
    # tauri embed build.frontendDist instead of compiling cfg(dev) against build.devUrl.
    run_in "$ROOT" cargo build --release --locked -p at-app --features custom-protocol
    run_in "$ROOT" cargo build --release --locked -p at-cli

    if (( ! DRY_RUN )); then
        for binary in "$TARGET_DIR/release/agentuna-app" "$TARGET_DIR/release/agentuna"; do
            [[ -f "$binary" ]] || fail "missing built binary: $binary"
        done
    fi

    # --- Assemble the portable tree ------------------------------------------

    echo "==> Assembling $STAGE"
    run rm -rf "$STAGE" "$CLI_STAGE"
    run install -d -m 0755 \
        "$STAGE/target/release" \
        "$STAGE/crates/at-app/icons" \
        "$STAGE/scripts" \
        "$STAGE/share/applications" \
        "$CLI_STAGE"
    run install -m 0755 "$TARGET_DIR/release/agentuna-app" "$STAGE/target/release/agentuna-app"
    run install -m 0755 "$TARGET_DIR/release/agentuna" "$STAGE/target/release/agentuna"
    for icon in "${ICONS[@]}"; do
        run install -m 0644 "$ROOT/crates/at-app/icons/$icon" "$STAGE/crates/at-app/icons/$icon"
    done
    run install -m 0755 "$ROOT/scripts/install-linux.sh" "$STAGE/scripts/install-linux.sh"
    run install -m 0644 "$ROOT/LICENSE" "$STAGE/LICENSE"
    run install -m 0755 "$TARGET_DIR/release/agentuna" "$CLI_STAGE/agentuna"
    run install -m 0644 "$ROOT/LICENSE" "$CLI_STAGE/LICENSE"

    if (( DRY_RUN )); then
        echo "+ write $STAGE/share/applications/agentuna.desktop from crates/at-app/src/app/linux.rs"
    else
        printf '%s\n' "$ENTRY" >"$STAGE/share/applications/agentuna.desktop"
        chmod 0644 "$STAGE/share/applications/agentuna.desktop"
    fi

    # --- Tarballs -------------------------------------------------------------

    echo "==> Creating the tarballs"
    run tar -czf "$DIST/$STAGE_NAME.tar.gz" -C "$DIST" "$STAGE_NAME"
    run tar -czf "$DIST/$CLI_STAGE_NAME.tar.gz" -C "$DIST" "$CLI_STAGE_NAME"
    run rm -rf "$STAGE" "$CLI_STAGE"
fi

# --- Optional Tauri bundles --------------------------------------------------

if (( BUNDLER )); then
    TAURI="$ROOT/ui/node_modules/.bin/tauri"
    [[ -x "$TAURI" ]] || fail "the Tauri CLI is missing; run: pnpm --dir ui install --frozen-lockfile (looked for $TAURI)"
    [[ -f "$ROOT/crates/at-app/tauri.linux.conf.json" ]] \
        || fail "missing crates/at-app/tauri.linux.conf.json"

    echo "==> Running the Tauri bundler for the .deb and the .AppImage"
    # `tauri bundle` packages the binary the cargo build already produced; the config override
    # sets bundle.targets to deb/appimage so the macOS `app` target keeps working.
    run_in "$ROOT/crates/at-app" "$TAURI" bundle --config tauri.linux.conf.json

    if (( DRY_RUN )); then
        echo "+ move $TARGET_DIR/release/bundle/deb/*.deb to $DIST/AgenTuna-$VERSION-linux-$ARCH.deb"
        echo "+ move $TARGET_DIR/release/bundle/appimage/*.AppImage to $DIST/AgenTuna-$VERSION-linux-$ARCH.AppImage"
        echo "==> Dry run: printed the plan; nothing was built or written"
        exit 0
    fi

    run install -d -m 0755 "$DIST"

    shopt -s nullglob
    debs=("$TARGET_DIR"/release/bundle/deb/*.deb)
    appimages=("$TARGET_DIR"/release/bundle/appimage/*.AppImage)
    shopt -u nullglob

    # A second run in the same target directory overwrites rather than accumulating, so more
    # than one match means a stale artifact and an ambiguous name.
    if (( ${#debs[@]} != 1 )); then
        fail "expected one .deb below $TARGET_DIR/release/bundle/deb, found ${#debs[@]}"
    fi
    if (( ${#appimages[@]} != 1 )); then
        fail "expected one .AppImage below $TARGET_DIR/release/bundle/appimage, found ${#appimages[@]}"
    fi
    run mv -f "${debs[0]}" "$DIST/AgenTuna-$VERSION-linux-$ARCH.deb"
    run mv -f "${appimages[0]}" "$DIST/AgenTuna-$VERSION-linux-$ARCH.AppImage"
fi

if (( DRY_RUN )); then
    echo "==> Dry run: printed the plan for dist/AgenTuna-$VERSION-linux-$ARCH; nothing was built or written"
    exit 0
fi

# --- Summary -----------------------------------------------------------------

echo "==> Release artifacts in $DIST"
for artifact in "$DIST/$STAGE_NAME.tar.gz" "$DIST/$CLI_STAGE_NAME.tar.gz" \
    "$DIST/AgenTuna-$VERSION-linux-$ARCH.deb" "$DIST/AgenTuna-$VERSION-linux-$ARCH.AppImage"; do
    if [[ -f "$artifact" ]]; then
        echo "    $(basename "$artifact")  $(du -h "$artifact" | awk '{print $1}')"
    fi
done
