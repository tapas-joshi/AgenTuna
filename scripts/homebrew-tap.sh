#!/bin/sh
# Generates the Homebrew cask and formula for one AgenTuna release from its SHA256SUMS file.
#
#   scripts/homebrew-tap.sh --version 0.1.0 --sums SHA256SUMS --out <tap-checkout>
#
# Writes <out>/Casks/agentuna.rb (the macOS Apple Silicon app plus the bundled `agentuna` CLI) and
# <out>/Formula/agentuna-cli.rb (the command-line tool alone: macOS Apple Silicon and Linux
# x86_64). Both download the files attached to the GitHub release and pin their SHA-256, so a
# changed asset fails the install. No network access and no Homebrew are needed to run this.
#
# The cask removes the quarantine attribute after install because the app is ad-hoc signed, not
# notarized (there is no Apple Developer ID yet); drop `postflight_steps` once releases are notarized.
set -eu

usage() {
  sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
}

version="" sums="" out=""
while [ $# -gt 0 ]; do
  case "$1" in
    --version) version="${2:?--version needs a value}"; shift 2 ;;
    --sums) sums="${2:?--sums needs a path}"; shift 2 ;;
    --out) out="${2:?--out needs a directory}"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done
[ -n "$version" ] && [ -n "$sums" ] && [ -n "$out" ] || { usage >&2; exit 2; }
case "$version" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "version must look like 0.1.0, got: $version" >&2; exit 2 ;;
esac
[ -f "$sums" ] || { echo "no such SHA256SUMS file: $sums" >&2; exit 2; }
[ -d "$out" ] || { echo "no such directory: $out" >&2; exit 2; }

sha_of() {
  # `sha256sum` output: "<64 hex>  <name>"; match the name exactly.
  value="$(awk -v name="$1" '$2 == name { print $1 }' "$sums")"
  case "$value" in
    [0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f][0-9a-f]*) ;;
    *) echo "no checksum for $1 in $sums" >&2; exit 1 ;;
  esac
  [ "${#value}" -eq 64 ] || { echo "malformed checksum for $1" >&2; exit 1; }
  printf '%s' "$value"
}

repo="tapas-joshi/AgenTuna"
dmg_sha="$(sha_of "AgenTuna-${version}-macos-arm64.dmg")"
cli_mac_sha="$(sha_of "agentuna-cli-${version}-macos-arm64.tar.gz")"
cli_linux_sha="$(sha_of "agentuna-cli-${version}-linux-x86_64.tar.gz")"

mkdir -p "$out/Casks" "$out/Formula"

cat >"$out/Casks/agentuna.rb" <<EOF
# Generated by scripts/homebrew-tap.sh in ${repo} for v${version}. Do not edit by hand.
cask "agentuna" do
  version "${version}"
  sha256 "${dmg_sha}"

  url "https://github.com/${repo}/releases/download/v#{version}/AgenTuna-#{version}-macos-arm64.dmg"
  name "AgenTuna"
  desc "Manage skills, MCP servers and rules for coding agents"
  homepage "https://github.com/${repo}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: :ventura

  app "AgenTuna.app"
  binary "#{appdir}/AgenTuna.app/Contents/Resources/bin/agentuna"

  # The app is ad-hoc signed and not notarized, so Gatekeeper would block the first launch.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/AgenTuna.app"]
  end

  caveats <<~CAVEATS
    AgenTuna is a preview build that is signed ad-hoc and not notarized; this cask clears the
    quarantine flag for you. The \`agentuna\` command is linked from the app bundle.
  CAVEATS
end
EOF

cat >"$out/Formula/agentuna-cli.rb" <<EOF
# Generated by scripts/homebrew-tap.sh in ${repo} for v${version}. Do not edit by hand.
class AgentunaCli < Formula
  desc "CLI for AgenTuna: skills, MCP servers and rules for coding agents"
  homepage "https://github.com/${repo}"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "https://github.com/${repo}/releases/download/v${version}/agentuna-cli-${version}-macos-arm64.tar.gz"
      sha256 "${cli_mac_sha}"
    end
  end

  on_linux do
    on_intel do
      url "https://github.com/${repo}/releases/download/v${version}/agentuna-cli-${version}-linux-x86_64.tar.gz"
      sha256 "${cli_linux_sha}"
    end
  end

  conflicts_with cask: "agentuna", because: "the cask already links an \`agentuna\` command"

  def install
    bin.install "agentuna"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/agentuna --version")
  end
end
EOF

echo "wrote $out/Casks/agentuna.rb and $out/Formula/agentuna-cli.rb for v${version}"
